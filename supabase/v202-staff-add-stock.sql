-- One-Line v202: STAFF RECEIVING ONLY. Run once in the EXISTING One-Line Supabase SQL Editor.
-- REQUIRED AFTER v198 migration. Atomic, positive-only stock adjustments; preserves checkout/sales functions.
-- This transaction never deletes catalogue items, orders, stock movements or customer data.
BEGIN;

-- Audit trail for the JSONB-stored inventory types; product stock changes also use stock_movements.
CREATE TABLE IF NOT EXISTS public.staff_stock_additions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_kind text NOT NULL,
  item_id uuid NOT NULL,
  option_id text,
  size_name text,
  qty_added integer NOT NULL CHECK (qty_added BETWEEN 1 AND 10000),
  previous_stock integer NOT NULL,
  new_stock integer NOT NULL,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.staff_stock_additions ENABLE ROW LEVEL SECURITY;
-- No direct insert/update/delete grants to authenticated clients: only the RPC below writes these records.
REVOKE ALL ON public.staff_stock_additions FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.staff_add_stock(
  p_kind text,
  p_id uuid,
  p_option text,
  p_size text,
  p_quantity integer
) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $function$
DECLARE
  v_before integer;
  v_after integer;
  v_product uuid;
  v_cfg jsonb;
  v_options jsonb;
  v_item public.custom_catalog_items%rowtype;
  v_variant jsonb;
  v_size_row jsonb;
  v_group text;
  v_group_name text;
  v_variant_idx integer;
  v_size_idx integer;
  v_matches integer := 0;
  v_groups text[];
BEGIN
  IF NOT public.has_role(ARRAY['admin','staff']) THEN
    RAISE EXCEPTION 'Only active staff or admin accounts can add stock';
  END IF;
  IF p_quantity IS NULL OR p_quantity<1 OR p_quantity>10000 THEN
    RAISE EXCEPTION 'Enter a quantity from 1 to 10,000';
  END IF;
  IF p_kind NOT IN ('product','product-variant','custom-size','printable-size') OR p_id IS NULL THEN
    RAISE EXCEPTION 'Invalid stock item type or ID';
  END IF;

  IF p_kind='product-variant' THEN
    SELECT product_id,stock INTO v_product,v_before
      FROM public.product_variants WHERE id=p_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Variant no longer exists'; END IF;
    IF v_before IS NULL OR v_before<0 OR v_before>2147483647-p_quantity THEN
      RAISE EXCEPTION 'Stock is invalid or exceeds supported range';
    END IF;
    v_after:=v_before+p_quantity;
    UPDATE public.product_variants SET stock=v_after WHERE id=p_id;
    -- Atomic parent increment avoids overwriting another concurrent receiving operation.
    UPDATE public.products SET stock=coalesce(stock,0)+p_quantity WHERE id=v_product;
    INSERT INTO public.stock_movements(product_id,product_variant_id,qty_delta,actor_id,reason)
      VALUES(v_product,p_id,p_quantity,auth.uid(),'Staff stock received (v202)');

  ELSIF p_kind='product' THEN
    SELECT stock INTO v_before FROM public.products WHERE id=p_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Product no longer exists'; END IF;
    IF EXISTS (SELECT 1 FROM public.product_variants WHERE product_id=p_id) THEN
      RAISE EXCEPTION 'Choose the exact product variant instead';
    END IF;
    IF v_before IS NULL OR v_before<0 OR v_before>2147483647-p_quantity THEN
      RAISE EXCEPTION 'Stock is invalid or exceeds supported range';
    END IF;
    v_after:=v_before+p_quantity;
    UPDATE public.products SET stock=v_after WHERE id=p_id;
    INSERT INTO public.stock_movements(product_id,qty_delta,actor_id,reason)
      VALUES(p_id,p_quantity,auth.uid(),'Staff stock received (v202)');

  ELSE
    SELECT * INTO v_item FROM public.custom_catalog_items WHERE id=p_id FOR UPDATE;
    IF NOT FOUND OR v_item.active IS FALSE THEN RAISE EXCEPTION 'Catalogue item unavailable'; END IF;
    IF nullif(btrim(p_size),'') IS NULL THEN RAISE EXCEPTION 'Choose a size'; END IF;
    v_options:=coalesce(v_item.fabric_options,'{}'::jsonb);

    IF p_kind='custom-size' THEN
      IF nullif(btrim(p_option),'') IS NULL THEN RAISE EXCEPTION 'Choose an exact variant'; END IF;
      v_cfg:=v_options->'uniform_config';
      IF jsonb_typeof(v_cfg)<>'object' THEN RAISE EXCEPTION 'Tracked uniform stock not found'; END IF;
      v_groups:=CASE WHEN v_cfg ? 'top' OR v_cfg ? 'bottom' THEN ARRAY['top','bottom'] ELSE ARRAY['items'] END;
      FOREACH v_group_name IN ARRAY v_groups LOOP
        FOR v_variant,v_variant_idx IN
          SELECT value,(ordinality-1)::integer FROM jsonb_array_elements(
            CASE WHEN jsonb_typeof(v_cfg->v_group_name)='array' THEN v_cfg->v_group_name ELSE '[]'::jsonb END
          ) WITH ORDINALITY LOOP
          IF v_variant->>'id' IS DISTINCT FROM p_option THEN CONTINUE; END IF;
          IF coalesce((v_variant->>'enabled')::boolean,true)=false THEN RAISE EXCEPTION 'Variant disabled'; END IF;
          FOR v_size_row,v_size_idx IN
            SELECT value,(ordinality-1)::integer FROM jsonb_array_elements(
              CASE WHEN jsonb_typeof(v_variant->'sizes')='array' THEN v_variant->'sizes' ELSE '[]'::jsonb END
            ) WITH ORDINALITY LOOP
            IF btrim(coalesce(v_size_row->>'size',''))<>btrim(p_size) THEN CONTINUE; END IF;
            v_matches:=v_matches+1;
            IF v_matches>1 THEN RAISE EXCEPTION 'Duplicate variant/size found'; END IF;
            IF coalesce((v_size_row->>'unlimited')::boolean,false) THEN RAISE EXCEPTION 'This size has unlimited stock'; END IF;
            IF v_size_row->>'stock' IS NULL THEN RAISE EXCEPTION 'This size has no tracked stock'; END IF;
            v_before:=(v_size_row->>'stock')::integer;
            IF v_before<0 OR v_before>2147483647-p_quantity THEN RAISE EXCEPTION 'Invalid stock amount'; END IF;
            v_after:=v_before+p_quantity;
            v_cfg:=jsonb_set(v_cfg,ARRAY[v_group_name,v_variant_idx::text,'sizes',v_size_idx::text,'stock'],to_jsonb(v_after),false);
          END LOOP;
        END LOOP;
      END LOOP;
      IF v_matches<>1 THEN RAISE EXCEPTION 'Exact variant and size not found'; END IF;
      v_options:=jsonb_set(v_options,'{uniform_config}',v_cfg,true);
    ELSE
      IF NOT EXISTS (
        SELECT 1 FROM public.custom_catalog_categories c
        WHERE c.id=v_item.category_id
          AND lower(btrim(regexp_replace(coalesce(c.name,''),'[-_[:space:]]+',' ','g')))
              = 'ready stock printable items'
      ) THEN RAISE EXCEPTION 'Choose a Ready Stock Printable item'; END IF;
      v_cfg:=v_options->'sportswear_sizes';
      IF jsonb_typeof(v_cfg)<>'array' THEN RAISE EXCEPTION 'Tracked printable sizes not found'; END IF;
      FOR v_size_row,v_size_idx IN SELECT value,(ordinality-1)::integer FROM jsonb_array_elements(v_cfg) WITH ORDINALITY LOOP
        IF btrim(coalesce(v_size_row->>'size',''))<>btrim(p_size) THEN CONTINUE; END IF;
        v_matches:=v_matches+1;
        IF v_matches>1 THEN RAISE EXCEPTION 'Duplicate printable size found'; END IF;
        IF coalesce((v_size_row->>'unlimited')::boolean,false) THEN RAISE EXCEPTION 'This size has unlimited stock'; END IF;
        IF v_size_row->>'stock' IS NULL THEN RAISE EXCEPTION 'This size has no tracked stock'; END IF;
        v_before:=(v_size_row->>'stock')::integer;
        IF v_before<0 OR v_before>2147483647-p_quantity THEN RAISE EXCEPTION 'Invalid stock amount'; END IF;
        v_after:=v_before+p_quantity;
        v_cfg:=jsonb_set(v_cfg,ARRAY[v_size_idx::text,'stock'],to_jsonb(v_after),false);
      END LOOP;
      IF v_matches<>1 THEN RAISE EXCEPTION 'Exact printable size not found'; END IF;
      v_options:=jsonb_set(v_options,'{sportswear_sizes}',v_cfg,true);
    END IF;
    UPDATE public.custom_catalog_items SET fabric_options=v_options,updated_at=now() WHERE id=p_id;
  END IF;

  INSERT INTO public.staff_stock_additions(item_kind,item_id,option_id,size_name,qty_added,previous_stock,new_stock,actor_id)
    VALUES(p_kind,p_id,p_option,p_size,p_quantity,v_before,v_after,auth.uid());
  RETURN v_after;
END;
$function$;

REVOKE ALL ON FUNCTION public.staff_add_stock(text,uuid,text,text,integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.staff_add_stock(text,uuid,text,text,integer) TO authenticated;
COMMIT;
NOTIFY pgrst, 'reload schema';
