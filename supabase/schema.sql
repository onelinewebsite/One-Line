create or replace function public.make_item_code() returns text language plpgsql as $$
declare chars text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; out_code text; i int;
begin
  loop
    out_code := '';
    for i in 1..6 loop out_code := out_code || substr(chars, 1 + floor(random()*length(chars))::int, 1); end loop;
    if out_code ~ '[A-Z]' and out_code ~ '[0-9]' and not exists(select 1 from public.products where code=out_code) and not exists(select 1 from public.subitems where code=out_code) then return out_code; end if;
  end loop;
end $$;

create or replace function public.apply_item_code() returns trigger language plpgsql as $$
begin
  if nullif(trim(new.barcode),'') is not null then
    new.code := trim(new.barcode);
  elsif nullif(trim(new.code),'') is null then
    new.code := public.make_item_code();
  else
    new.code := upper(trim(new.code));
    if new.code !~ '^[A-Z0-9]{6}$' or new.code !~ '[A-Z]' or new.code !~ '[0-9]' then
      raise exception 'Manual item code must be exactly 6 alphanumeric characters and contain at least one letter and one number';
    end if;
  end if;
  new.code := upper(trim(new.code));
  if tg_table_name='products' and exists(select 1 from public.subitems s where s.code=new.code) then raise exception 'Item code already exists on a subitem'; end if;
  if tg_table_name='subitems' and exists(select 1 from public.products p where p.code=new.code) then raise exception 'Item code already exists on a product'; end if;
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists trg_products_code on public.products;
