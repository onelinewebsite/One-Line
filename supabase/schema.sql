drop trigger if exists trg_subitems_code on public.subitems;
create trigger trg_subitems_code before insert or update on public.subitems for each row execute function public.apply_item_code();

create or replace function public.has_role(roles text[]) returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles p where p.id=auth.uid() and p.active and p.role=any(roles));
$$;

