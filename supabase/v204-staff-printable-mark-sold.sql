-- One-Line v204: Allow authenticated active staff/admin to mark a finite
-- Ready Stock Printable garment size as sold, without an order.
-- Run ONCE in the existing One-Line Supabase SQL Editor AFTER v198 and v202.
-- Does not change checkout, orders, pricing, or existing stock functions.
BEGIN;

CREATE TABLE IF NOT EXISTS public.staff_printable_sales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id uuid NOT NULL,
  size_name text NOT NULL,
  qty_sold integer NOT NULL CHECK(qty_sold BETWEEN 1 AND 10000),
  previous_stock integer NOT NULL,
  new_stock integer NOT NULL,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.staff_printable_sales ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.staff_printable_sales FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.staff_mark_printable_sold(
  p_item uuid, p_size text, p_quantity integer
) RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $function$
DECLARE
  v_item public.custom_catalog_items%rowtype;
  v_size_row jsonb;
  v_before integer;
  v_after integer;
  v_matches integer := 0;
  v_category text;
BEGIN
  IF NOT public.has_role(ARRAY['admin','staff']) THEN
    RAISE EXCEPTION 'Only active staff or admin accounts can mark stock as sold';
  END IF;
  IF p_item IS NULL OR NULLIF(BTRIM(p_size),'') IS NULL THEN
    RAISE EXCEPTION 'Choose a valid item and size';
  END IF;
  IF p_quantity IS NULL OR p_quantity<1 OR p_quantity>10000 THEN
    RAISE EXCEPTION 'Quantity must be between 1 and 10000';
  END IF;
  SELECT * INTO v_item FROM public.custom_catalog_items WHERE id=p_item FOR UPDATE;
  IF NOT FOUND OR v_item.active IS FALSE THEN
    RAISE EXCEPTION 'Ready Stock item is unavailable';
  END IF;
  SELECT LOWER(BTRIM(REGEXP_REPLACE(COALESCE(name,''),'[-_[:space:]]+',' ','g')))
    INTO v_category FROM public.custom_catalog_categories WHERE id=v_item.category_id;
  IF v_category IS DISTINCT FROM 'ready stock printable items' THEN
    RAISE EXCEPTION 'This is not a Ready Stock Printable item';
  END IF;
  IF JSONB_TYPEOF(v_item.fabric_options->'sportswear_sizes') IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Size stock settings are missing';
  END IF;
  FOR v_size_row IN SELECT value FROM JSONB_ARRAY_ELEMENTS(v_item.fabric_options->'sportswear_sizes') LOOP
    IF BTRIM(COALESCE(v_size_row->>'size','')) <> BTRIM(p_size) THEN CONTINUE; END IF;
    v_matches := v_matches+1;
    IF v_matches>1 THEN RAISE EXCEPTION 'Duplicate sizes in this item'; END IF;
    IF COALESCE((v_size_row->>'unlimited')::boolean,false)
       OR v_size_row->>'stock' IS NULL THEN
      RAISE EXCEPTION 'This size has unlimited/untracked stock';
    END IF;
    v_before := (v_size_row->>'stock')::integer;
  END LOOP;
  IF v_matches<>1 THEN RAISE EXCEPTION 'Exact size not found'; END IF;
  IF v_before IS NULL OR v_before<0 OR v_before<p_quantity THEN
    RAISE EXCEPTION 'Insufficient stock for this size';
  END IF;
  -- Existing v198 inventory implementation performs the actual atomic deduction.
  PERFORM public.one_line_adjust_printable_inventory(
    JSONB_BUILD_OBJECT('itemId',p_item,'sizeQuantities',JSONB_BUILD_OBJECT(BTRIM(p_size),p_quantity)),
    -1
  );
  v_after := v_before-p_quantity;
  INSERT INTO public.staff_printable_sales(item_id,size_name,qty_sold,previous_stock,new_stock,actor_id)
    VALUES(p_item,BTRIM(p_size),p_quantity,v_before,v_after,auth.uid());
  RETURN v_after;
END;
$function$;
REVOKE ALL ON FUNCTION public.staff_mark_printable_sold(uuid,text,integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.staff_mark_printable_sold(uuid,text,integer) TO authenticated;
COMMIT;
NOTIFY pgrst, 'reload schema';
